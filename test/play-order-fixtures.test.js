import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import { comparePlays } from "../src/play-order.js";
import { createReplayFrames } from "../src/replay.js";

const root = new URL("./fixtures/games/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json", root), "utf8"));
const fixtures = await Promise.all(manifest.map(async (entry) => {
  const summary = JSON.parse(gunzipSync(await readFile(new URL(entry.file, root))));
  const drives = [...(summary.drives?.previous ?? []), summary.drives?.current].filter(Boolean);
  const plays = [...new Map(drives.flatMap((drive) => drive.plays ?? []).map((play) => [play.id, play])).values()];
  return { entry, summary, plays };
}));

// Independently recorded opening/closing football events, not an expectation
// generated by the production comparator or a sequence-number sort.
const boundaries = {
  "401873010": ["40187301040", "40187301063", "40187301086", "4018730104183", "4018730104206", "4018730104228"],
  "401873016": ["40187301640", "40187301668", "40187301693", "4018730164284", "4018730164295", "4018730164320"],
  "401873012": ["40187301240", "40187301257", "40187301287", "4018730123890", "4018730123912", "4018730123934"],
  "401873020": ["40187302040", "40187302057", "40187302082", "4018730204213", "4018730204224", "4018730204255"],
  "401873022": ["40187302240", "40187302263", "40187302288", "4018730223919", "4018730223941", "4018730223965"],
  "401856732": ["4018567323", "40185673212", "40185673216", "401856732899", "401856732903", "401856732909"],
  "401856835": ["4018568353", "40185683512", "40185683516", "401856835855", "401856835858", "401856835864"],
  "401858496": ["4018584963", "40185849612", "40185849615", "401858496714", "401858496719", "401858496725"],
  "401856727": ["4018567273", "40185672712", "40185672717", "401856727758", "401856727761", "401856727766"],
  "401856731": ["4018567313", "40185673112", "40185673117", "401856731822", "401856731823", "401856731828"],
};

for (const { entry, plays } of fixtures) {
  test(`${entry.name}: opening events and final snaps/marker stay ordered regardless of input order`, () => {
    const expected = boundaries[entry.id];
    for (const input of [plays, [...plays].reverse()]) {
      const sorted = [...input].sort(comparePlays);
      assert.deepEqual([...sorted.slice(0, 3), ...sorted.slice(-3)].map((play) => play.id), expected);
    }
  });
}

const correctedWindows = {
  // The NFL timeout's timestamp is one second later than the ensuing rush.
  "401873016": [["4018730163895", "4018730163906"]],
  "401856732": [
    ["401856732407", "401856732413", "401856732411"],
    ["401856732650", "401856732464", "401856732647"],
    ["401856732856", "401856732854", "401856732860", "401856732858"],
  ],
  // These same-sequence timeouts have impossible increasing game clocks.
  "401856835": [["401856835722", "401856835739", "401856835740"]],
  "401858496": [["401858496556", "401858496561"]],
  "401856727": [["401856727356", "401856727363"]],
  "401856731": [["401856731214", "401856731221"]],
};

for (const [id, windows] of Object.entries(correctedWindows)) {
  test(`${id}: corrected clocks, revised wallclocks and reused sequences preserve football order`, () => {
    const { plays } = fixtures.find(({ entry }) => entry.id === id);
    for (const expected of windows) {
      assert.deepEqual(plays.filter((play) => expected.includes(play.id)).reverse().sort(comparePlays)
        .map((play) => play.id), expected);
    }
  });
}

test("Texas interception precedes the receiving offense's penalty despite the clock correction", () => {
  const { plays } = fixtures.find(({ entry }) => entry.id === "401856732");
  assert.deepEqual(plays.filter((play) => ["401856732421", "401856732429"].includes(play.id))
    .sort(comparePlays).map((play) => play.id), ["401856732421", "401856732429"]);
});

const indianaOvertime = [
  "401858496673", "401858496678", "401858496688", "401858496686",
  "401858496691", "401858496697", "401858496700", "401858496707",
  "401858496710", "401858496714", "401858496719", "401858496725",
];

test("Indiana untimed overtime keeps the timeout after the touchdown and the reused-sequence end marker last", () => {
  const { plays } = fixtures.find(({ entry }) => entry.id === "401858496");
  assert.deepEqual(plays.filter((play) => play.period.number === 5).sort(comparePlays).map((play) => play.id), indianaOvertime);
});

test("Indiana overtime replay starts tied and does not expose the touchdown score early", () => {
  const { entry, summary } = fixtures.find(({ entry }) => entry.id === "401858496");
  const frames = createReplayFrames(summary, { id: entry.id, league: entry.league, teamId: entry.awayTeamId })
    .filter((frame) => frame.spotlight.period === 5);
  assert.deepEqual(frames.map((frame) => frame.spotlight.plays[0].id), indianaOvertime);
  assert.deepEqual(frames.map((frame) => [frame.spotlight.selectedTeam.score, frame.spotlight.opponent.score]),
    [[6, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6], [13, 6]]);
});
