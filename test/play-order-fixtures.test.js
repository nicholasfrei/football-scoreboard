for (const [id, windows] of Object.entries(correctedWindows)) {
  test(`${id}: corrected clocks, revised wallclocks and reused sequences preserve football order`, () => {
    const { plays } = fixtures.find(({ entry }) => entry.id === id);
    for (const expected of windows) {
      assert.deepEqual(plays.filter((play) => expected.includes(play.id)).reverse().sort(comparePlays)
        .map((play) => play.id), expected);
    }
  });
}

